-- OAuth provider accounts are permitted at the Supabase signup layer; app invitation checks enforce access.
create or replace function public.hook_restrict_rankviz_signup(event jsonb)
returns jsonb
language plpgsql
stable
as $$
declare
  provider text;
begin
  provider := coalesce(event->'user'->'app_metadata'->>'provider','');
  if provider <> 'google' then
    return jsonb_build_object('error', jsonb_build_object('http_code', 403, 'message', 'Only Google sign-in is supported.'));
  end if;
  return jsonb_build_object('decision', 'continue');
end;
$$;

